for _task in DEMO_REVIEWS:
    _phrases = REVIEW_PHRASES.get(_task["title"])
    if _phrases:
        _task["templates"] = _phrases

DEMO_TASKS = DEMO_REVIEWS + DEMO_VIDEOS + DEMO_POLLS

# Версия набора демо-заданий. Когда добавляются новые — увеличиваем, и они
# один раз доезжают на уже работающий сервер. Удалённые админом задания
# обратно не возвращаются: версия к тому моменту уже записана.
DEMO_VERSION = "6"


async def seed_if_empty() -> None:
    existing = await db.all_tasks()
    if not existing:
        for position, task in enumerate(DEMO_TASKS):
            await db.add_task(position=position, rotating=True, **task)
        await db.set_setting("demo_tasks_version", DEMO_VERSION)
    elif await db.get_setting("demo_tasks_version") != DEMO_VERSION:
        # Обновление: добавляем только те демо-задания, которых ещё нет.
        titles = {task["title"] for task in existing}
        for position, task in enumerate(DEMO_TASKS):
            if task["title"] not in titles:
                await db.add_task(position=position, rotating=True, **task)
        # На уже живой базе задания заведены до появления ротации — включаем
        # её тем, что пришли из этого набора. Задания, добавленные админом
        # руками, не трогаем: они должны висеть в ленте постоянно.
        await db.mark_rotating([task["title"] for task in DEMO_TASKS])
        # И подтягиваем новые подсказки к отзывам, которые уже заведены:
        # старые три готовых текста делали все отзывы одинаковыми.
        await db.refresh_templates(DEMO_REVIEWS)
        await db.set_setting("demo_tasks_version", DEMO_VERSION)

    # Витринный рейтинг обновляем при каждом старте: суммы могут поменяться,
    # а участники всё равно ненастоящие (у них отрицательные id).
    for index, (name, earned) in enumerate(DEMO_TOP, start=1):
        await db.upsert_user(-index, full_name=name)
        await db.set_demo_totals(-index, earned)
