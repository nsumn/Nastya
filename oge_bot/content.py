# --------------------------------------------------------------------------- #
#  Хелперы доступа
# --------------------------------------------------------------------------- #
def get_subject(subject_id: str) -> Subject | None:
    return next((s for s in SUBJECTS if s.id == subject_id), None)


def get_topic(subject_id: str, topic_id: str) -> Topic | None:
    subject = get_subject(subject_id)
    if subject is None:
        return None
    return next((t for t in subject.topics if t.id == topic_id), None)


def all_materials() -> list[Material]:
    """Плоский список всех материалов по всем предметам — для ежедневной рассылки."""
    result: list[Material] = []
    for subject in SUBJECTS:
        for topic in subject.topics:
            result.extend(topic.materials)
    return result
