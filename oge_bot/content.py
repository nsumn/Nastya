"""Учебные материалы для подготовки к ОГЭ.

Структура данных:

    SUBJECTS = [Subject, ...]
        Subject.topics = [Topic, ...]
            Topic.materials = [Material, ...]

Чтобы добавить предмет/тему/материал — просто допиши сюда. Всё меню,
навигация и ежедневная рассылка строятся из этих данных автоматически.

Material поддерживает:
    * text  — текст урока/конспекта (обязательно);
    * file  — путь к локальному файлу или URL документа (необязательно),
              бот отправит его как документ;
    * url   — внешняя ссылка (необязательно), добавится кнопкой/строкой.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Material:
    id: str
    title: str
    text: str
    file: str | None = None
    url: str | None = None


@dataclass(frozen=True)
class Topic:
    id: str
    title: str
    materials: list[Material] = field(default_factory=list)


@dataclass(frozen=True)
class Subject:
    id: str
    title: str
    emoji: str
    topics: list[Topic] = field(default_factory=list)


