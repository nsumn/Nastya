// Daily news video: write parts_day/cues.txt (Lumean SFX + chained music) from the scene's own timeline (y_times.js + y_cues.js). Run from earthstop/: node tools/day_cues.mjs
import fs from 'fs';
const src = fs.readFileSync('parts_day/y_times.js', 'utf8') + fs.readFileSync('parts_day/y_cues.js', 'utf8') + '\nreturn { CUES, ENDC, T_END };';
const { CUES, ENDC, T_END } = new Function(src)();
let out = `# daily news video — generated by tools/day_cues.mjs (voice mixed separately)\nmusic news0 0.0 0.32 30.0\nmusic news1 29.8 0.32 ${(T_END - 0.3).toFixed(2)}\n`;
for (const [t, n, g] of CUES) out += `${t.toFixed(2)} ${n} ${g}\n`;
fs.writeFileSync('parts_day/cues.txt', out); console.log('cues', CUES.length, 'T_END', T_END.toFixed(2));
