"""US news-map video: TTS word timestamps → timeline. In: out/<name>/voice.mp3 + result.json. Out: out/<name>/voice.wav (LEAD s of hook first,
extra pauses after chosen sentences) and parts_news/n_times.js: SENT = start of every sentence, WORDS = [t0, t1, word], VO_END.
Usage: python3 tools/news_timing.py <name> <lead> <pause list "i:sec,i:sec"> [MAXGAP=0.18 cuts every longer silence between words down to it] [OUTJS=parts_day/y_times.js] """
import os
import json, re, sys, subprocess, numpy as np
from scipy.io import wavfile
name, LEAD = sys.argv[1], float(sys.argv[2]); PA = {int(a): float(b) for a, b in (x.split(':') for x in sys.argv[3].split(','))} if len(sys.argv) > 3 and sys.argv[3] else {}
D = f'out/{name}/'; W = json.load(open(D + 'result.json'))['words']
sents, cur = [], []
for w in W:
    cur.append(w)
    if re.search(r'[.?!]$', w['word'].strip()): sents.append(cur); cur = []
if cur: sents.append(cur)
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', D + 'voice.mp3', '-ac', '1', '-ar', '44100', D + 'voice_raw.wav'], check=True)
sr, a = wavfile.read(D + 'voice_raw.wav'); a = a.astype(np.float32)
MAXGAP = float(os.environ.get('MAXGAP', '0'))
if MAXGAP > 0:   # cut long silences: keep MAXGAP/2 after the word and MAXGAP/2 before the next (short crossfade)
    cuts = [(W[i]['end'] + MAXGAP / 2, W[i + 1]['start'] - MAXGAP / 2) for i in range(len(W) - 1) if W[i + 1]['start'] - W[i]['end'] > MAXGAP]
    def sq(t): return t - sum(min(max(t - c0, 0), c1 - c0) for c0, c1 in cuts)
    keep, prev = [], 0
    for c0, c1 in cuts: keep.append(a[prev:int(c0 * sr)]); prev = int(c1 * sr)
    keep.append(a[prev:]); f = int(0.006 * sr)
    for k in keep[1:]:
        if len(k) > f: k[:f] *= np.linspace(0, 1, f)
    a = np.concatenate(keep)
    for w in W: w['start'], w['end'] = sq(w['start']), sq(w['end'])
    print('cut', len(cuts), 'silences')
ins = []   # (orig time, extra seconds) inserted in the middle of the gap after sentence i
for i, s in enumerate(sents):
    if i in PA and i + 1 < len(sents): ins.append(((s[-1]['end'] + sents[i + 1][0]['start']) / 2, PA[i]))
def remap(t): return t + LEAD + sum(L for c, L in ins if t > c)
parts, prev = [np.zeros(int(LEAD * sr), np.float32)], 0
for c, L in ins: i = int(c * sr); parts += [a[prev:i], np.zeros(int(L * sr), np.float32)]; prev = i
parts.append(a[prev:]); out = np.concatenate(parts); wavfile.write(D + 'voice.wav', sr, out.astype(np.int16))
SENT = [round(remap(s[0]['start']), 3) for s in sents]; WORDS = [[round(remap(w['start']), 3), round(remap(w['end']), 3), w['word'].strip()] for w in W]
open(os.environ.get('OUTJS', 'parts_news/n_times.js'), 'w').write('// generated by tools/news_timing.py — do not edit\nconst SENT = ' + json.dumps(SENT) + ';\nconst WORDS = ' + json.dumps(WORDS) + ';\nconst VO_END = ' + str(round(len(out) / sr, 3)) + ';\n')
print('sentences', len(sents), 'VO_END', round(len(out) / sr, 2)); print(SENT)
